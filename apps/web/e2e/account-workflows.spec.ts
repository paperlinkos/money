import { expect, test } from '@playwright/test'
import sharp from 'sharp'

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLr9wAAAABJRU5ErkJggg==', 'base64')
const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\ntrailer\n<<>>\n%%EOF\n')
const monday = '2030-01-07'

function unique(testName: string, project: string) {
  return `${testName}-${project}-${Date.now().toString(36)}`.toLowerCase().replace(/[^a-z0-9-]/g, '-')
}

async function registerProvider(page: any, id: string, name: string) {
  await page.goto('/tools/booking/account')
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(`${id}@test.local`)
  await page.getByLabel('Password').fill('safe-password-123')
  await page.getByLabel('Business name').fill(name)
  await page.getByLabel('Booking page slug').fill(id)
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${name} Booking` })).toBeVisible()
}

test('Booking provider and client complete an account-backed appointment flow', async ({ page, browser }, testInfo) => {
  const id = unique('booking-browser', testInfo.project.name)
  const business = `Booking Studio ${testInfo.project.name}`
  await registerProvider(page, id, business)

  await page.getByLabel('Service name').fill('Browser Consultation')
  await page.getByLabel('Description').fill('A browser acceptance booking service')
  await page.getByLabel('NGN').fill('5000')
  await page.getByLabel('Minutes').fill('60')
  await page.getByLabel('Buffer').fill('0')
  await page.getByRole('button', { name: 'Add service' }).click()
  await expect(page.getByText('Service saved.')).toBeVisible()

  await page.getByRole('button', { name: '+ Working day' }).click()
  await page.locator('form').filter({ hasText: 'Booking page & availability' }).locator('select').first().selectOption('1')
  const timeInputs = page.locator('input[type="time"]')
  await timeInputs.nth(0).fill('09:00')
  await timeInputs.nth(1).fill('17:00')
  await page.getByRole('button', { name: '+ Regular break' }).click()
  await timeInputs.nth(2).fill('12:00')
  await timeInputs.nth(3).fill('13:00')
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByText('Availability settings saved.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: `${business} Booking` })).toBeVisible()

  const clientContext = await browser.newContext({ viewport: testInfo.project.name === 'mobile' ? { width: 390, height: 844 } : { width: 1280, height: 900 } })
  const client = await clientContext.newPage()
  await client.goto(`/book/${id}`)
  await expect(client.getByRole('heading', { name: business })).toBeVisible()
  await client.getByLabel('Date').fill(monday)
  const timeSelect = client.locator('select').nth(1)
  await expect(timeSelect.locator('option')).toHaveCount(13)
  await expect(timeSelect.getByRole('option', { name: '12:00' })).toHaveCount(0)
  const originalSlot = await timeSelect.locator('option').nth(1).textContent()
  expect(originalSlot).toBeTruthy()
  await timeSelect.selectOption({ label: originalSlot! })
  await client.getByLabel('Your name').fill('Booking Browser Client')
  await client.getByLabel('Phone').fill('08000000000')
  await client.getByRole('button', { name: 'Send booking request' }).click()
  await expect(client.getByText(/Request received with reference BK-/)).toBeVisible()

  await page.reload()
  await expect(page.getByText('Booking Browser Client')).toBeVisible()
  await page.getByRole('button', { name: 'Confirm' }).click()
  await expect(page.getByText(/Confirmed/)).toBeVisible()

  await client.reload()
  await client.getByLabel('Date').fill(monday)
  await expect(timeSelect.getByRole('option', { name: originalSlot! })).toHaveCount(0)

  await page.getByRole('button', { name: 'Reschedule' }).click()
  const rescheduleTime = page.getByLabel('Available time')
  await expect(rescheduleTime.locator('option')).not.toHaveCount(1)
  const newSlot = (await rescheduleTime.locator('option').allTextContents()).find((slot) => slot !== 'Choose a time' && slot !== originalSlot)
  expect(newSlot).toBeTruthy()
  await rescheduleTime.selectOption({ label: newSlot! })
  await page.getByRole('button', { name: 'Save new time' }).click()
  await expect(page.getByText('Appointment rescheduled.')).toBeVisible()

  await client.reload()
  await client.getByLabel('Date').fill(monday)
  await expect(timeSelect.getByRole('option', { name: originalSlot! })).toHaveCount(1)
  await expect(timeSelect.getByRole('option', { name: newSlot! })).toHaveCount(0)

  await page.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('NGN').fill('6500')
  await page.getByRole('button', { name: 'Save service' }).click()
  await expect(page.getByText('₦6,500')).toBeVisible()
  await page.getByRole('button', { name: 'Deactivate' }).click()
  await expect(page.getByText('Inactive')).toBeVisible()

  const otherProvider = await browser.newContext()
  const otherPage = await otherProvider.newPage()
  await registerProvider(otherPage, unique('other-provider', testInfo.project.name), 'Other Provider')
  const isolatedServices = await otherPage.request.get('/api/booking/services')
  expect(await isolatedServices.json()).toEqual([])
  await otherProvider.close()

  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Provider sign in' })).toBeVisible()
  await clientContext.close()
})

test('ProofFlow creator and client complete a versioned review workflow', async ({ page, browser }, testInfo) => {
  const id = unique('proof-browser', testInfo.project.name)
  await registerProvider(page, id, `Proof Studio ${testInfo.project.name}`)
  await page.goto('/tools/proof')
  await page.getByLabel('Project name').fill('Browser Proof Project')
  await page.getByLabel('Client name').fill('Proof Browser Client')
  await page.getByLabel('Client email').fill('client@example.test')
  await page.getByLabel('Description').fill('A private browser acceptance review project.')
  await page.getByRole('button', { name: 'Create project' }).click()
  await page.getByRole('button', { name: /Browser Proof Project/ }).click()
  await expect(page.getByRole('heading', { name: 'Browser Proof Project' })).toBeVisible()

  const newDeliverable = page.locator('section').filter({ hasText: 'Deliverables' }).locator('input[type="file"]').first()
  await newDeliverable.setInputFiles({ name: 'browser-proof.png', mimeType: 'image/png', buffer: png })
  await page.getByRole('button', { name: 'Upload file' }).click()
  await expect(page.getByText('File uploaded.')).toBeVisible()
  await newDeliverable.setInputFiles({ name: 'brief.pdf', mimeType: 'application/pdf', buffer: pdf })
  await page.getByRole('button', { name: 'Upload file' }).click()
  await expect(page.getByText('File uploaded.')).toBeVisible()
  await expect(page.getByText('browser-proof.png', { exact: true })).toBeVisible()
  await expect(page.getByText('brief.pdf', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Generate review link' }).click()
  const reviewLinks = page.getByRole('heading', { name: 'Review links' }).locator('..')
  await expect(reviewLinks).toContainText('/review/')
  const linkText = await reviewLinks.innerText()
  const token = linkText.match(/\/review\/([A-Za-z0-9_-]{43})/)?.[1]
  expect(token).toBeTruthy()

  const clientContext = await browser.newContext({ viewport: testInfo.project.name === 'mobile' ? { width: 390, height: 844 } : { width: 1280, height: 900 } })
  const client = await clientContext.newPage()
  await client.goto(`/review/${token}`)
  await expect(client.getByRole('heading', { name: 'Browser Proof Project' })).toBeVisible()
  await expect(client.locator('img')).toHaveCount(1)
  await expect(client.locator('iframe')).toHaveCount(1)
  const fileUrl = await client.locator('img').getAttribute('src')
  expect(fileUrl).toContain(`/api/public/review/${token}/files/`)
  await client.getByPlaceholder('Display name').fill('Review Client')
  await client.getByRole('button', { name: 'Continue' }).click()
  const imageReview = client.locator('article').filter({ hasText: 'browser-proof.png' })
  await imageReview.getByPlaceholder('Leave a comment').fill('Please brighten the image.')
  await imageReview.getByRole('button', { name: 'Send' }).click()
  await expect(client.getByText('Your comment was sent.')).toBeVisible()
  await imageReview.getByRole('button', { name: 'Favorite image' }).click()
  await expect(imageReview.getByRole('button', { name: 'Remove favorite' })).toBeVisible()
  await imageReview.getByPlaceholder('Describe what should change').fill('Please use the alternate crop.')
  await imageReview.getByRole('button', { name: 'Request' }).click()
  await expect(client.getByText('Your change request was sent.')).toBeVisible()

  await page.reload()
  await page.getByRole('button', { name: /Browser Proof Project/ }).click()
  await expect(page.getByRole('heading', { name: 'Client feedback' })).toBeVisible()
  await expect(page.getByText('Please brighten the image.')).toBeVisible()
  await expect(page.getByText('1 unique selection')).toBeVisible()
  await expect(page.getByText('Please use the alternate crop.')).toBeVisible()

  const imageDeliverable = page.locator('article').filter({ hasText: 'browser-proof.png' })
  await imageDeliverable.locator('input[type="file"]').setInputFiles({ name: 'browser-proof-v2.png', mimeType: 'image/png', buffer: Buffer.concat([png, Buffer.from('v2')]) })
  await expect(page.getByText('New version uploaded.')).toBeVisible()
  await client.reload()
  await expect(client.getByRole('button', { name: 'Approve Version 2' })).toBeVisible()
  client.once('dialog', (dialog) => void dialog.accept())
  await client.getByRole('button', { name: 'Approve Version 2' }).click()
  await expect(client.getByText('Version approved.')).toBeVisible()

  await page.reload()
  await page.getByRole('button', { name: /Browser Proof Project/ }).click()
  await expect(page.getByText('Version 2 · Current version')).toBeVisible()
  const currentDeliverable = page.locator('article').filter({ hasText: 'browser-proof-v2.png' })
  await currentDeliverable.locator('input[type="file"]').setInputFiles({ name: 'browser-proof-v3.png', mimeType: 'image/png', buffer: Buffer.concat([png, Buffer.from('v3')]) })
  await expect(page.getByText('New version uploaded.')).toBeVisible()
  await client.reload()
  await expect(client.getByRole('button', { name: 'Approve Version 3' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Browser Proof Project/ }).click()
  await expect(page.getByText('Version 2 · Superseded version')).toBeVisible()

  page.once('dialog', (dialog) => void dialog.accept())
  await page.getByRole('button', { name: 'Revoke' }).click()
  await expect(page.getByText('Review link revoked.')).toBeVisible()
  await client.reload()
  await expect(client.getByRole('heading', { name: 'Review unavailable' })).toBeVisible()
  const revokedFile = await client.request.get(fileUrl!)
  expect(revokedFile.status()).toBe(404)
  await client.goto(`/review/${'x'.repeat(30)}`)
  await expect(client.getByRole('heading', { name: 'Review unavailable' })).toBeVisible()
  await clientContext.close()
})

test('Protected gallery shows clients a watermarked preview until originals are released', async ({ page, browser }, testInfo) => {
  const id = unique('protected-browser', testInfo.project.name)
  await registerProvider(page, id, `Ada Studio ${testInfo.project.name}`)
  await page.goto('/tools/proof')
  await page.getByLabel('Project name').fill('Protected Wedding')
  await page.getByLabel('Client name').fill('Protected Client')
  await page.getByRole('button', { name: 'Create project' }).click()
  await page.getByRole('button', { name: /Protected Wedding/ }).click()
  await expect(page.getByLabel('Protect images in this gallery')).toBeChecked()

  const photo = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="3000" height="2000"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#7c2d12"/><stop offset="0.5" stop-color="#f59e0b"/><stop offset="1" stop-color="#0f172a"/></linearGradient></defs><rect width="3000" height="2000" fill="url(#g)"/></svg>')).jpeg({ quality: 92 }).toBuffer()
  const chooser = page.locator('section').filter({ hasText: 'Deliverables' }).locator('input[type="file"]').first()
  await chooser.setInputFiles({ name: 'wedding.jpg', mimeType: 'image/jpeg', buffer: photo })
  await page.getByRole('button', { name: 'Upload file' }).click()
  await expect(page.getByText('File uploaded.')).toBeVisible()
  await chooser.setInputFiles({ name: 'brief.pdf', mimeType: 'application/pdf', buffer: pdf })
  await page.getByRole('button', { name: 'Upload file' }).click()
  await expect(page.locator('article').filter({ hasText: 'brief.pdf' })).toBeVisible()
  await expect(page.getByText('PDFs are not watermarked')).toBeVisible()
  await page.getByLabel('Watermark text').fill('Ada Proofs')
  await page.getByRole('button', { name: 'Save watermark' }).click()
  await expect(page.getByText('Watermark saved.')).toBeVisible()
  await page.locator('section').filter({ hasText: 'Protected previews' }).first().screenshot({ path: testInfo.outputPath('creator.png') })

  await page.getByRole('button', { name: 'Generate review link' }).click()
  const reviewLinks = page.getByRole('heading', { name: 'Review links' }).locator('..')
  await expect(reviewLinks).toContainText('/review/')
  const token = (await reviewLinks.innerText()).match(/\/review\/([A-Za-z0-9_-]{43})/)?.[1]
  expect(token).toBeTruthy()

  const clientContext = await browser.newContext({ viewport: testInfo.project.name === 'mobile' ? { width: 390, height: 844 } : { width: 1280, height: 900 } })
  const client = await clientContext.newPage()
  await client.goto(`/review/${token}`)
  const shown = client.locator('article').filter({ hasText: 'wedding.jpg' }).locator('img')
  await expect.poll(() => shown.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(1600)
  await expect(client.getByText('This is a watermarked preview.')).toBeVisible()
  await expect(client.getByRole('link', { name: 'Download original' })).toHaveCount(0)
  await expect(client.getByRole('link', { name: 'Download file' })).toHaveCount(1)
  expect(await client.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await client.screenshot({ path: testInfo.outputPath('client.png') })
  const previewUrl = (await shown.getAttribute('src'))!
  expect((await client.request.get(`${previewUrl}/original`)).status()).toBe(403)
  expect(Buffer.compare(await (await client.request.get(previewUrl)).body(), photo)).not.toBe(0)
  expect(Buffer.compare(await (await page.request.get(`/api/proof/files/${previewUrl.split('/').at(-1)}`)).body(), photo)).toBe(0)

  page.once('dialog', (dialog) => void dialog.accept())
  await page.getByRole('button', { name: 'Release originals' }).click()
  await expect(page.getByText('Originals released.')).toBeVisible()
  await client.reload()
  const [download] = await Promise.all([client.waitForEvent('download'), client.getByRole('link', { name: 'Download original' }).click()])
  expect(download.suggestedFilename()).toBe('wedding.jpg')
  const saved = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of saved) chunks.push(chunk as Buffer)
  expect(Buffer.compare(Buffer.concat(chunks), photo)).toBe(0)
  await clientContext.close()
})
